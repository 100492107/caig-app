export const SOCIAL_SALES_DOCTRINE = `
VIEWER-FIRST SALES PSYCHOLOGY
- Define the viewer before the hook: who is this for, what do they want, avoid, understand or become, what would stop the scroll, what proof would make them believe, and what action naturally follows?
- Sell the transformation/outcome, not the object, feature or production process.
- Lead with the result, decision, lesson, discovery, tension or change. Explain the mechanism after attention is earned.
- Use a clear point of view the creator can honestly defend. Do not manufacture conviction.
- Treat objections, questions and disagreement as content research. Strong comments can become the next post.
- A CTA should be a logical next step: save, share, answer, watch the next part, explore, or buy when the offer genuinely fits.
- Never turn every post into a sales pitch.

2026 SOCIAL DIRECTION
- Discovery matters: build for recommendation feeds, search, curiosity and adjacent discovery, not only existing followers.
- Search matters: state the subject naturally in the spoken hook, on-screen text and caption where useful. Never keyword-stuff.
- Community matters: comments, reactions, questions and audience language are creative inputs.
- Originality matters: AI can accelerate production, but the account needs original perspective, voice, story and execution.
- Commerce matters: content should be able to move from discovery to trust to action when a real product fit exists.
- Think like a media company: recurring series, recognisable characters, owned audience, reusable IP and a clear path from attention to business.

CONTENT FUNNEL
ATTENTION → RECOGNITION → VALUE → TRUST → DESIRE → ACTION → PROOF → REPEAT
Not every post contains every stage. The portfolio does.

SHORT-FORM DEFAULT
0–2s: promise, claim, visual pattern interrupt or immediate result.
2–6s: context and why it matters.
6–20s: useful point, story or tension.
20–35s: proof, example, contrast or consequence.
Final beat: payoff + natural next step.
Use visual changes when the idea changes. Do not cut just to look busy.

VISUAL EXECUTION
- Face/voice is the trust anchor.
- Use supporting screenshots, photos or B-roll when they add proof or context.
- Keep on-screen text readable without sound.
- Use one main idea per video.
- Prefer believable mid-action scenes over generic posing.
- Avoid AI-luxury backdrop filler and decorative cuts with no purpose.

COMMERCE
Problem/desire → lived context → product bridge → evidence/fit → natural CTA.
The product is the bridge to an outcome. Never invent price, discount, review, commission, result or eligibility.

ORIGINALITY / REFERENCE RULE
Study high-performing media for mechanism, structure and audience psychology. Do not copy distinctive wording, identity, footage, branding or execution.

REQUIRED PLANNING FIELDS
viewer, viewer_outcome, belief_reason, objection_or_question, search_intent, next_step, comment_seed, series_follow_up


OCTOBER 2026 PLATFORM UPDATE
- TikTok continues to emphasise curiosity, search, community and the why behind purchase decisions.
- TikTok's recent comment features make the comment area a richer creative surface; use genuine audience responses as inputs for future content.
- TikTok is expanding AI-assisted discovery-to-action tooling and measurement.
- Meta continues to prioritise original creator content and AI-assisted creator tools.
- Operational response: design content for discovery + search + community + commerce, while preserving original creator perspective and materially original execution.

DECISION RULE
Prefer the concept with the clearest audience outcome, strongest believable reason to care, most specific point of view, cleanest visual story, most natural next step and best chance of becoming a repeatable series.
`;

